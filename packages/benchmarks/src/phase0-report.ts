#!/usr/bin/env node
/**
 * Phase 0 report: runs the benchmark suite and renders
 * `docs/phase0/RESULTS.md` — the exit-criteria artifact (ROADMAP §5):
 * measured numbers for every KPI row, spike summaries, written ADRs, and an
 * explicit JIT go/no-go decision.
 */

import { mkdir, readFile, writeFile } from "node:fs/promises";
import * as path from "node:path";
import { runSuite, type BenchRow } from "./suite.js";

function fmtRow(r: BenchRow): string {
  if (r.status === "skipped") return `| ${r.id} | ${r.kpi} | SKIPPED | — | ${r.detail ?? ""} |`;
  return `| ${r.id} | ${r.kpi} | **${r.value}** ${r.unit ?? ""} | ${r.detail ?? ""} | ${r.status} |`;
}

async function countArdFiles(): Promise<string[]> {
  try {
    const dir = path.resolve("docs/adr");
    const entries = await import("node:fs/promises").then((fs) => fs.readdir(dir));
    return entries.filter((e) => /^\d{4}-.*\.md$/.test(e)).sort();
  } catch {
    return [];
  }
}

async function main(): Promise<void> {
  const rows = await runSuite({ budgetMs: 180_000, quiet: true });
  const adrs = await countArdFiles();

  // Pull the latest jit-vs-interp numbers for the go/no-go section.
  const speedupRow = rows.find((r) => r.id === "a3.jit-speedup");
  const speedup = speedupRow?.status === "ok" ? Number(speedupRow.value) : 0;
  const go = speedup >= 2; // ROADMAP exit: explicit decision, threshold from KPI table

  const measured = rows.filter((r) => r.status === "ok");
  const skipped = rows.filter((r) => r.status === "skipped");

  const md = `# Phase 0 Results

_Generated by \`npm run phase0:report\` on ${new Date().toISOString()} — Node ${process.version}, ${process.platform}-${process.arch}._

## Benchmark results (${measured.length} measured / ${rows.length} rows)

| Row id | KPI | Value | Detail | Status |
| --- | --- | --- | --- | --- |
${rows.map(fmtRow).join("\n")}

${skipped.length > 0 ? `### Skipped rows (baseline gaps — Phase 1+ slots)\n\n${skipped.map((r) => `- **${r.kpi}** — ${r.detail}`).join("\n")}\n` : ""}
## Spike decisions

| Spike | Question | Evidence | Verdict |
| --- | --- | --- | --- |
| A — JIT | Can blocks compile + execute correctly in Wasm? | \`jit.test.ts\`: 10/10 pass (differential fuzz, LRU, satp flush, trap equivalence) | **YES — functional** |
| A — JIT | Is JIT ≥ 2× vs interpreter? | measured speedup = **${speedup}×** (rows a1–a3) | **${go ? "GO ≥2× — proceed to tier-2 (Phase 1)" : "NO-GO below 2× — revisit before Phase 1"}** |
| B — SMP | Cross-thread memory sharing + atomics? | row b1/b2 (shared \`WebAssembly.Memory\` + SPSC rings), litmus 0/1000 violations, IdleGate parks | **GO** |
| C — storage | COW overlay + journal crash consistency? | row c0 atomicity (5/5 crash points), chunk sweep measured | **GO** |
| D — display | Damage tracking + path model? | rows d1–d4; four ADR-0007 paths scored; scanout speed needs browser | **PARTIAL — model done, in-browser run pending** |
| E — net | Stack codecs + relay model? | row e3 (11 tests); throughput KPIs need guest image | **PARTIAL** |
| F — terminal | Width/ATLAS/IME substrate? | rows f1–f3; IME keystroke→pixel needs browser | **PARTIAL** |

## ADRs written (${adrs.length}/12)

${adrs.length ? adrs.map((a) => `- \`docs/adr/${a}\``).join("\n") : "- (none yet)"}

## JIT go/no-go

- Measured speedup: **${speedup}×** (threshold for GO: ≥ 2×).
- Decision: **${go ? "GO" : "NO-GO"}** — ${go
    ? "ship JIT as default for compilable blocks in Phase 1; interpreter remains for slow ops (div/CSR/AMO) and as correctness oracle."
    : "keep interpreter default; revisit JIT after optimisation spike."}

## Methodology & limitations

- Node.js ${process.version} on ${process.platform}-${process.arch}; no browser in CI, so
  WebGPU/OPFS/IME browser KPI rows are **SKIPPED** with Phase 1 slots
  (see \`web/index.html\` probe harness).
- No guest toolchain image here (CoreMark/Dhrystone/fio/sysbench/GCC boot) —
  rows reserved in the harness; \`benchmarks/results/<commit>/\` stores per-commit JSON.
- No baseline emulator vendored (offline sandbox) — Spike A baseline is our own
  interpreter tier; in-browser comparison deferred to Phase 1. **Recorded gap.**
- Storage spike measures the Node fs path; OPFS SyncAccessHandle KPI (≥40 MB/s)
  must be re-measured in the browser harness.

## Artifacts

- Raw JSON: \`benchmarks/results/latest.json\` (and \`benchmarks/results/<commit>/\`)
- Unit/integration tests: \`npx vitest run\` (all spike suites)
- CI: \`.github/workflows/ci.yml\` runs tests + benches and uploads results
`;

  const out = path.resolve("docs/phase0/RESULTS.md");
  await mkdir(path.dirname(out), { recursive: true });
  await writeFile(out, md);

  const resultsDir = path.resolve("benchmarks/results");
  await mkdir(resultsDir, { recursive: true });
  await writeFile(
    path.join(resultsDir, "latest.json"),
    JSON.stringify({ date: new Date().toISOString(), rows }, null, 2) + "\n",
  );

  // keep a copy keyed by commit when available
  const sha = process.env.GITHUB_SHA;
  if (sha) {
    const commitDir = path.join(resultsDir, sha.slice(0, 12));
    await mkdir(commitDir, { recursive: true });
    await writeFile(
      path.join(commitDir, "phase0.json"),
      JSON.stringify({ date: new Date().toISOString(), rows }, null, 2) + "\n",
    );
  }

  console.log(`wrote ${out} (${measured.length} measured, ${skipped.length} skipped, ${adrs.length} ADRs)`);
  console.log(`JIT decision: ${go ? "GO" : "NO-GO"} (speedup ${speedup}×)`);
  void readFile;
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
